"""
evals/search_eval.py — Eval suite for the search planner stage.

Two types of checks:

1. HEURISTIC EVALS (free, no API calls):
   Structural checks on the search plan — does it have enough queries?
   Does it use site: operators? Does it specify geography? Does the
   audience summary mention the right demographics?

2. LLM-AS-JUDGE EVALS (costs API calls):
   Claude evaluates whether the search plan is genuinely intelligent
   for the given brand + niche — are the queries niche-specific?
   Would they find trending content, not evergreen?

Run:
    python -m evals.search_eval              # heuristic only (free)
    python -m evals.search_eval --llm-judge  # heuristic + LLM judge
    python -m evals.search_eval --live       # full pipeline with real Serper calls
"""


def eval_plan_heuristic(plan: dict, fixture: dict) -> list[dict]:
    """
    Run heuristic checks on a search plan. No API calls needed.

    Returns a list of {check, passed, detail} dicts.
    """
    results = []
    queries = plan.get("queries", [])

    # Check 1: Has 4-8 queries
    count = len(queries)
    results.append({
        "check": "query_count",
        "passed": 4 <= count <= 8,
        "detail": f"Got {count} queries (expected 4-8)",
    })

    # Check 2: At least one site: query (niche-specific targeting)
    site_queries = [q for q in queries if "site:" in q.get("query", "")]
    results.append({
        "check": "has_site_queries",
        "passed": len(site_queries) >= 1,
        "detail": f"Found {len(site_queries)} site:-targeted queries",
    })

    # Check 3: Has at least one news endpoint query
    news_queries = [q for q in queries if q.get("endpoint") == "news"]
    results.append({
        "check": "has_news_query",
        "passed": len(news_queries) >= 1,
        "detail": f"Found {len(news_queries)} news-endpoint queries",
    })

    # Check 4: Geography is specified
    geo = plan.get("geography", {})
    has_geo = bool(geo.get("country_code"))
    results.append({
        "check": "has_geography",
        "passed": has_geo,
        "detail": f"Geography: {geo.get('country_code', 'missing')} — {geo.get('reasoning', 'no reasoning')}",
    })

    # Check 5: Audience summary mentions expected keywords
    audience = plan.get("audience_summary", "").lower()
    expected = fixture.get("expected_audience_keywords", [])
    matched = [kw for kw in expected if kw.lower() in audience]
    results.append({
        "check": "audience_mentions_demographics",
        "passed": len(matched) >= 2,
        "detail": f"Audience summary matched {len(matched)}/{len(expected)} keywords: {matched}",
    })

    # Check 6: Source hints cover expected platforms
    source_hints = " ".join(q.get("source_hint", "") for q in queries).lower()
    query_text = " ".join(q.get("query", "") for q in queries).lower()
    combined = source_hints + " " + query_text
    expected_sources = fixture.get("expected_sources", [])
    matched_sources = [s for s in expected_sources if s.lower() in combined]
    results.append({
        "check": "covers_niche_sources",
        "passed": len(matched_sources) >= 2,
        "detail": f"Covered {len(matched_sources)}/{len(expected_sources)} expected sources: {matched_sources}",
    })

    # Check 7: Every query has a rationale
    has_rationale = all(q.get("rationale") for q in queries)
    results.append({
        "check": "all_queries_have_rationale",
        "passed": has_rationale,
        "detail": "All queries have rationale" if has_rationale else "Some queries missing rationale",
    })

    # Check 8: Mix of general and specific queries
    general = [q for q in queries if "site:" not in q.get("query", "")]
    results.append({
        "check": "has_general_queries",
        "passed": len(general) >= 2,
        "detail": f"Found {len(general)} general (non-site:) queries",
    })

    return results


def eval_plan_llm_judge(plan: dict, fixture: dict) -> dict:
    """
    Use Claude to judge the quality of a search plan. Costs one API call.

    Returns a dict with scores and reasoning.
    """
    from tools.writer import get_client, get_text
    from tools.search_planner import PLANNER_MODEL

    system_prompt = """You are evaluating a search plan generated by an AI agent.
The agent was given a brand's guidelines and a niche, and produced a list
of search queries to find trending topics.

Score the plan on 5 criteria (1-10 each):

1. NICHE AWARENESS — Do the queries target platforms and sources that actually
   matter for this specific niche? (e.g., Billboard for Music, Hacker News for Tech)
2. AUDIENCE FIT — Do the queries consider who the brand's audience is?
   (age, interests, values, where they spend time online)
3. FRESHNESS FOCUS — Would these queries find what's trending RIGHT NOW,
   or would they return evergreen/old content?
4. DIVERSITY — Is there a good mix of source types? (news, social, niche platforms, general)
5. PRACTICALITY — Are the queries well-formed and likely to return useful results
   from a Google search API? (not too broad, not too narrow)

Respond with ONLY a JSON object:
{
    "niche_awareness": {"score": 8, "reasoning": "..."},
    "audience_fit": {"score": 7, "reasoning": "..."},
    "freshness_focus": {"score": 9, "reasoning": "..."},
    "diversity": {"score": 8, "reasoning": "..."},
    "practicality": {"score": 7, "reasoning": "..."},
    "overall": 7.8,
    "biggest_gap": "One sentence on the most important thing the plan is missing"
}"""

    plan_text = json.dumps(plan, indent=2)
    user_message = f"""Evaluate this search plan.

--- BRAND + NICHE ---
Niche: {fixture['niche']}
Brand guidelines (summary): {fixture['brand_guidelines'][:500]}

--- SEARCH PLAN ---
{plan_text}

Score it. Respond with JSON only."""

    response = get_client().messages.create(
        model=PLANNER_MODEL,
        max_tokens=1024,
        system=system_prompt,
        messages=[{"role": "user", "content": user_message}],
    )

    text = get_text(response)
    stripped = text.strip()
    if stripped.startswith("```"):
        lines = stripped.split("\n")
        lines = [l for l in lines if not l.strip().startswith("```")]
        stripped = "\n".join(lines)

    try:
        return json.loads(stripped)
    except json.JSONDecodeError:
        return {"error": "Could not parse judge response", "raw": text[:300]}


def eval_results_heuristic(results: list[dict]) -> list[dict]:
    """
    Run heuristic checks on search results (requires live API calls to have run).
    """
    checks = []

    # Check 1: Got enough results
    checks.append({
        "check": "result_count",
        "passed": len(results) >= 10,
        "detail": f"Got {len(results)} results (expected >= 10)",
    })

    # Check 2: Source diversity — results come from 3+ distinct domains
    sources = set()
    for r in results:
        source = r.get("source", "").lower()
        if source and source != "google trends":
            sources.add(source)
    checks.append({
        "check": "source_diversity",
        "passed": len(sources) >= 3,
        "detail": f"Results from {len(sources)} distinct sources: {list(sources)[:10]}",
    })

    # Check 3: Has results from niche platforms (found_by != "general")
    niche_results = [r for r in results if r.get("found_by", "general") not in ("general", "Google Trends")]
    checks.append({
        "check": "has_niche_platform_results",
        "passed": len(niche_results) >= 3,
        "detail": f"Found {len(niche_results)} results from niche-specific queries",
    })

    # Check 4: No empty titles or snippets
    empty = [r for r in results if not r.get("title") or not r.get("snippet")]
    checks.append({
        "check": "no_empty_fields",
        "passed": len(empty) == 0,
        "detail": f"{len(empty)} results with empty title/snippet",
    })

    return checks


def print_results(fixture_name: str, checks: list[dict], judge: dict = None):
    """Pretty-print eval results for one fixture."""
    print(f"\n{'='*60}")
    print(f"  FIXTURE: {fixture_name}")
    print(f"{'='*60}")

    passed = sum(1 for c in checks if c["passed"])
    total = len(checks)
    print(f"\n  Heuristic checks: {passed}/{total} passed\n")

    for c in checks:
        status = "PASS" if c["passed"] else "FAIL"
        print(f"  [{status}] {c['check']}: {c['detail']}")

    if judge:
        print(f"\n  LLM Judge Scores:")
        for key in ["niche_awareness", "audience_fit", "freshness_focus", "diversity", "practicality"]:
            entry = judge.get(key, {})
            if isinstance(entry, dict):
                score = entry.get("score", "?")
                reason = entry.get("reasoning", "")
                print(f"    {key}: {score}/10 — {reason}")
        print(f"\n  Overall: {judge.get('overall', '?')}/10")
        print(f"  Biggest gap: {judge.get('biggest_gap', '?')}")


def run_eval(use_llm_judge: bool = False, live: bool = False):
    """Run the full eval suite across all fixtures."""
    from tools.search_planner import plan_searches

    print("\n" + "="*60)
    print("  SEARCH PLANNER EVAL SUITE")
    print("="*60)
    print(f"  Mode: {'LIVE (API calls)' if live else 'heuristic only'}")
    print(f"  LLM judge: {'ON' if use_llm_judge else 'OFF'}")
    print(f"  Fixtures: {len(FIXTURES)}")

    all_scores = []

    for fixture in FIXTURES:
        print(f"\n  Running: {fixture['name']}...")

        # Generate search plan
        plan = plan_searches(fixture["niche"], fixture["brand_guidelines"])

        # Heuristic checks on the plan
        checks = eval_plan_heuristic(plan, fixture)

        # LLM-as-judge (optional)
        judge = None
        if use_llm_judge:
            print(f"  Running LLM judge...")
            judge = eval_plan_llm_judge(plan, fixture)

        # Live search results (optional)
        if live:
            from tools.search import search_trending_agentic
            print(f"  Running live search...")
            results, metadata = search_trending_agentic(fixture["niche"], fixture["brand_guidelines"])
            result_checks = eval_results_heuristic(results)
            checks.extend(result_checks)

        print_results(fixture["name"], checks, judge)

        score = {
            "fixture": fixture["name"],
            "heuristic_pass_rate": sum(1 for c in checks if c["passed"]) / len(checks),
            "checks": checks,
        }
        if judge and "overall" in judge:
            score["llm_judge_overall"] = judge["overall"]
        all_scores.append(score)

    # Summary
    print(f"\n{'='*60}")
    print(f"  SUMMARY")
    print(f"{'='*60}")
    for s in all_scores:
        judge_str = f", LLM judge: {s['llm_judge_overall']}/10" if "llm_judge_overall" in s else ""
        print(f"  {s['fixture']}: {s['heuristic_pass_rate']:.0%} heuristic pass rate{judge_str}")

    avg_pass = sum(s["heuristic_pass_rate"] for s in all_scores) / len(all_scores)
    print(f"\n  Average heuristic pass rate: {avg_pass:.0%}")

    # Save results
    results_dir = Path("evals/results")
    results_dir.mkdir(exist_ok=True)
    from datetime import datetime
    results_file = results_dir / f"search_eval_{datetime.now().strftime('%Y-%m-%d_%H%M%S')}.json"
    with open(results_file, "w") as f:
        json.dump(all_scores, f, indent=2, default=str)
    print(f"\n  Results saved to: {results_file}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Search planner eval suite")
    parser.add_argument("--llm-judge", action="store_true", help="Enable LLM-as-judge scoring (costs API calls)")
    parser.add_argument("--live", action="store_true", help="Run live Serper searches (costs API calls)")
    args = parser.parse_args()

    from dotenv import load_dotenv
    load_dotenv()

    run_eval(use_llm_judge=args.llm_judge, live=args.live)
